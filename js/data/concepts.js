/* ── essay architecture ──────────────────────────────────────────
   The Essay Architect's vocabulary. Each role has a job, a test for whether it has
   done it, and the failure mode students actually produce. */
EN.DATA.paragraphRoles = [
  { id:"thesis", name:"Thesis", icon:"🎯", where:"introduction",
    job:"State the argument the whole essay will prove.",
    test:"Could a competent person disagree with this sentence? If not, it is a summary.",
    fail:"'This essay will explore how Orwell uses techniques to show themes.' Names no position." },
  { id:"topic", name:"Topic sentence", icon:"📌", where:"paragraph opening",
    job:"State this paragraph's contribution to the thesis, conceptually.",
    test:"Does it make a claim about the text rather than announcing a subject?",
    fail:"'Orwell uses symbolism in the novel.' A subject, not a claim." },
  { id:"evidence", name:"Evidence", icon:"❝", where:"paragraph body",
    job:"Supply the shortest quotation that carries the point.",
    test:"Is it integrated grammatically, and is it three to eight words rather than three lines?",
    fail:"A block quotation dropped in as its own sentence, doing the paragraph's thinking for it." },
  { id:"analysis", name:"Analysis", icon:"⚙️", where:"paragraph body",
    job:"Explain how the named technique produces the effect.",
    test:"Is there a mechanism — a 'because', a 'so that', a 'which forces the reader to'?",
    fail:"Restating the quotation in different words, which is the single commonest Band 4 move." },
  { id:"link", name:"Link", icon:"🔗", where:"paragraph close",
    job:"Return to the module concept and to the thesis.",
    test:"Does it name the concept and say what this paragraph has established about it?",
    fail:"Repeating the topic sentence. A link should have moved somewhere." },
  { id:"transition", name:"Transition", icon:"➡️", where:"between paragraphs",
    job:"Carry the argument forward rather than announcing a new subject.",
    test:"Does it depend on what the previous paragraph proved?",
    fail:"'Furthermore, another technique used is…' Additive, not developmental." },
  { id:"return", name:"Conceptual return", icon:"↩️", where:"conclusion",
    job:"Restate what has been proved, and what follows from it.",
    test:"Does it say something the introduction could not have said?",
    fail:"Reprinting the thesis with the word 'therefore' in front of it." },
  { id:"counter", name:"Counter-position", icon:"⚖️", where:"anywhere",
    job:"Name the strongest reading against yours, and answer it.",
    test:"Is the version you named the good one, or a straw man?",
    fail:"Omitting it entirely — which costs most in 'discuss', 'evaluate' and 'to what extent'." }
];

